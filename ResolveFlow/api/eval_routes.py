"""Read-only Product Evaluation endpoints.

They only serve report files already produced by `scripts/run_product_eval.py`;
no request ever runs the evaluation or calls a model.
"""
import json
from pathlib import Path
from typing import Literal, Optional

from fastapi import APIRouter, HTTPException

ROOT = Path(__file__).resolve().parents[1]
REPORTS = ROOT / "data/eval/reports"
RUNS = {
    "current": REPORTS / "product_eval_latest.json",
    "baseline": REPORTS / "product_eval_baseline.json",
    "holdout": REPORTS / "product_eval_holdout_latest.json",
    "holdout_baseline": REPORTS / "product_eval_holdout_baseline.json",
}
Run = Literal["current", "baseline", "holdout", "holdout_baseline"]
router = APIRouter(prefix="/eval", tags=["Evaluation (read-only reports)"])
_cache = {}


def _load(run):
    path = RUNS[run]
    if not path.exists():
        return None
    mtime = path.stat().st_mtime
    if _cache.get(run, (None,))[0] != mtime:
        _cache[run] = (mtime, json.loads(path.read_text(encoding="utf-8")))
    return _cache[run][1]


def _summary(report):
    if not report:
        return None
    keys = ("run_id", "label", "generated_at", "git_commit", "git_dirty", "mode", "scope", "dataset", "metrics",
            "headline", "category_breakdown", "bad_case_summary", "baseline_comparison")
    return {k: report.get(k) for k in keys}


def _component():
    path = REPORTS / "latest_metrics.json"
    if not path.exists():
        return None
    data = json.loads(path.read_text(encoding="utf-8"))
    m = data.get("metrics", {})
    pick = ["intent_accuracy", "intent_case_count", "macro_f1", "routing_accuracy", "routing_case_count", "routing_eval_mode",
            "rag_top_1_hit_rate", "rag_top_3_hit_rate", "rag_mrr", "rag_query_count", "rag_retriever_mode",
            "knowledge_expectation_accuracy", "eval_pass_rate", "eval_result_count", "multi_agent_routing_accuracy", "supervisor_case_count"]
    return {"generated_at": data.get("timestamp"), "dataset_note": data.get("dataset_note"),
            "scope_note": "Full-backend component evaluation on the internal golden set (RAG measured with the ChromaDB hybrid retriever of the full backend, not the BM25 recruiting Demo). Not regenerated by the Product Evaluation.",
            "metrics": {k: m.get(k) for k in pick if k in m}}


def _fix_log():
    path = ROOT / "data/product_eval/fix_log.json"
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


@router.get("/product/latest")
def latest():
    current = _load("current")
    if not current:
        raise HTTPException(404, "No product evaluation report. Run scripts/run_product_eval.py first.")
    return {"current": _summary(current), "baseline": _summary(_load("baseline")),
            "holdout": {"current": _summary(_load("holdout")), "baseline": _summary(_load("holdout_baseline"))},
            "fix_log": _fix_log(), "component": _component()}


@router.get("/product/cases")
def cases(run: Run = "current", status: Optional[Literal["passed", "failed"]] = None, failure_type: Optional[str] = None,
          category: Optional[str] = None):
    report = _load(run)
    if not report:
        raise HTTPException(404, f"No report for run '{run}'")
    rows = []
    for c in report["cases"]:
        if status and c["result"].lower() != status:
            continue
        if failure_type and c.get("failure_type") != failure_type:
            continue
        if category and c["category"] != category:
            continue
        first = next((t.get("text") for t in c["trace"] if t["kind"] == "user"), "")
        rows.append({"id": c["id"], "category": c["category"], "title": c["title"], "result": c["result"],
                     "failure_type": c.get("failure_type"), "root_cause": c.get("root_cause"),
                     "user_turns": c["user_turns"], "first_message": first})
    return {"run": run, "run_id": report["run_id"], "count": len(rows), "cases": rows}


@router.get("/product/cases/{case_id}")
def case_detail(case_id: str, run: Run = "current"):
    report = _load(run)
    if not report:
        raise HTTPException(404, f"No report for run '{run}'")
    case = next((c for c in report["cases"] if c["id"] == case_id), None)
    if not case:
        raise HTTPException(404, "Case not found")
    analysis = next((b for b in report["bad_cases"] if b["case_id"] == case_id), None)
    return {"run": run, "run_id": report["run_id"], "mode": report["mode"], "case": case, "bad_case": analysis}
